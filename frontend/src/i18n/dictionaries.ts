export const guessLang = (c?: string) => {
  const code = (c || '').toLowerCase();
  if (
    [
      'ru',
      'uk',
      'be',
      'kk',
    ].includes(code)
  ) {
    return 'ru';
  }
  for (const k of [
    'de',
    'fr',
    'it',
    'zh',
  ]) {
    if (code.startsWith(k)) {
      return k;
    }
  }
  return 'en';
};
